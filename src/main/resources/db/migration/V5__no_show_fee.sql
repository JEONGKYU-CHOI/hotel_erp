-- =============================================================================
-- V5 : 노쇼 위약금 (no-show fee)  ★ 노쇼 과금 정교화 · D-037 ★
-- =============================================================================
--   노쇼를 "도착 후의 늦은 취소"로 보고 취소와 같은 정책(CancellationPolicy)으로 위약금을
--   계산해 예약에 스냅샷으로 남긴다. 취소 위약금(cancellation_fee, V4)과 대칭이다.
--
--   야간마감(V2·D-026)의 첫날 폴리오 게시와는 다른 관점의 값이다:
--     · reservation_night.posted  = 폴리오에 실제 게시된 숙박 라인(마감이 남긴다)
--     · reservation.no_show_fee    = 정책상 노쇼에 물려야 할 위약금(이 스냅샷)
--   둘의 정합(게시액 vs 위약금)은 정산(폴리오, 후속 범위)이 맞춘다. 마감은 검증된 핵심
--   과제(멱등성 ③)라 건드리지 않는다.
--
--   NULL = 아직 노쇼가 아니거나 위약금 미적용. 0 = 위약금 없는 노쇼(예: penalty_rate 0 정책).
-- =============================================================================

ALTER TABLE reservation
    ADD COLUMN no_show_fee DECIMAL(12,2) NULL
        COMMENT '노쇼 위약금 스냅샷 (D-037). NULL=미적용, 0=위약금 없음'
        AFTER cancellation_fee;
