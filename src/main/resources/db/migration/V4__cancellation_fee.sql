-- =============================================================================
-- V4 : 취소 위약금 (cancellation fee)  ★ 취소 과금 정교화 · D-037 ★
-- =============================================================================
--   취소 시점의 위약금을 예약 행에 스냅샷으로 남긴다. 위약금 계산의 근거값
--   (rate_plan.refundable · cancel_deadline_days · penalty_rate)은 요금정책이
--   나중에 바뀔 수 있으므로(RatePlan.update 주석), 확정된 금액을 예약에 굳혀 둔다 —
--   reservation_night 가 예약 시점 요금을 스냅샷하는 것과 같은 규율(D-005).
--
--   NULL 의 의미: 아직 취소되지 않았거나(진행 중 예약), 무료 취소(위약금 0 은 0 으로
--   기록하고, NULL 은 "위약금 계산이 적용되지 않은 예약"을 뜻한다). HOLD 취소는 미결제라
--   위약금 0 을 기록한다(ReservationCancelService 참조).
--
--   실제 환불 실행(토스 결제취소 API 호출)은 이 스냅샷을 근거로 하는 후속 범위다 —
--   여기서는 "얼마를 물리고 얼마를 돌려줄지"의 판정과 기록까지만 한다.
-- =============================================================================

ALTER TABLE reservation
    ADD COLUMN cancellation_fee DECIMAL(12,2) NULL
        COMMENT '취소 위약금 스냅샷 (D-037). NULL=미적용/미취소, 0=무료취소'
        AFTER cancel_reason;
